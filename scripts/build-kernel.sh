#!/usr/bin/env bash
# ANEXOMAIL WASM KERNEL build (Rule 52): Rust -> wasm32, public/kernel/anexo-kernel-<version>.wasm + SHA-256 pin (src/lib/kernel/pin.gen.ts).
# Server par Rust nahi chahiye: built .wasm repo mein commit hota hai; yeh script sirf developer machine / CI par chalti hai.
# Kernel ka version Cargo.toml mein hai; naya module = web-wasm/src/lib.rs MODULES + version bump (test dono ka mel check karta hai).
set -euo pipefail
cd "$(dirname "$0")/.."
export CARGO_HTTP_CAINFO="${CARGO_HTTP_CAINFO:-/root/.ccr/ca-bundle.crt}"
OFFLINE="${KERNEL_OFFLINE:---offline}"
( cd web-wasm && cargo test $OFFLINE -q 2>&1 | tail -3 && cargo build --release --target wasm32-unknown-unknown $OFFLINE -q )
VER="$(grep -m1 '^version' web-wasm/Cargo.toml | cut -d'"' -f2)"
OUT="public/kernel/anexo-kernel-$VER.wasm"
mkdir -p public/kernel
# purane versions hata do (sirf naya shipped rehta hai)
find public/kernel -name 'anexo-kernel-*.wasm' ! -name "anexo-kernel-$VER.wasm" -delete
cp web-wasm/target/wasm32-unknown-unknown/release/anexo_kernel.wasm "$OUT"
SHA="$(sha256sum "$OUT" | cut -d' ' -f1)"
cat > src/lib/kernel/pin.gen.ts <<EOF
// GENERATED by scripts/build-kernel.sh — haath se mat badlo. Kernel wasm ka SHA-256 pin (loader mismatch par inkaar karta hai).
export const KERNEL_PIN = {
  version: "$VER",
  url: "/kernel/anexo-kernel-$VER.wasm",
  sha256: "$SHA",
} as const;
EOF
echo "kernel $VER -> $OUT ($(stat -c%s "$OUT") bytes) sha256 $SHA"
echo "-- Dastoor (E90): is release ko darj karo, 3 round pass hone ke BAAD (naya E<n> SQL ya founder-run):"
echo "select public.kernel_release_publish('$VER', '$SHA', array[$(grep -o '"[a-z0-9]*@[0-9]*"' web-wasm/src/lib.rs | sort -u | tr '"' "'" | paste -sd, -)], 'notes');"
