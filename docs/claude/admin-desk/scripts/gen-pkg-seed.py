#!/usr/bin/env python3
"""D5a-2: build sql/AD6b.sql (registry seed) from the published landing-page list src/lib/plans.ts. Features + limits only, never a price.
usage: python3 docs/claude/admin-desk/scripts/gen-pkg-seed.py   (needs bun; run from the repo root)"""
import json, re, subprocess, hashlib, os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
raw = subprocess.check_output(["bun", "-e", 'import {WORKSPACE_PLANS,AI_PRICED_PLANS} from "./src/lib/plans.ts"; console.log(JSON.stringify([...WORKSPACE_PLANS,...AI_PRICED_PLANS].map(p=>({id:p.id,name:p.name,features:p.features}))))'], cwd=ROOT, text=True)
plans = {p["id"]: p for p in json.loads(raw)}
# limits exactly as the landing page prints them (source line noted); null = the page states no fixed cap
LIM = {
 "basic":        ({"seats": 5,   "storage_gb": 15,    "attachment_mb": 25, "mailboxes": 3},  "Up to 5 users; 3 mailboxes, 15GB shared storage; attachments up to 25MB"),
 "pro":          ({"seats": 20,  "storage_gb": 300,   "attachment_mb": 35, "mailboxes": 10}, "Up to 20 users; 10 mailboxes, 300GB shared storage; attachments up to 35MB"),
 "business":     ({"seats": 60,  "storage_gb": 1500,  "attachment_mb": 45, "chat_file_mb": 500},  "Up to 60 users; 1.5TB shared storage; attachments 45MB; 500MB max file sending"),
 "business_pro": ({"seats": 570, "storage_gb": 10000, "attachment_mb": 60, "chat_file_mb": 1500}, "Up to 570 users; 10TB shared storage; attachments 60MB; 1.5GB max file sending"),
 "ai_pro":       ({"seats": 60,  "storage_gb": 1500,  "attachment_mb": 45, "chat_file_mb": 500},  "All Business platform features included (Business limits)"),
 "ai_business":  ({"seats": 60,  "storage_gb": 1500,  "attachment_mb": 45, "chat_file_mb": 1500}, "Business platform + 1.5GB max file sending"),
 "ai_executive": ({"seats": None, "storage_gb": 1000, "attachment_mb": 60, "chat_file_mb": 1500}, "Business Pro platform: unlimited users + 1TB; 1.5GB file sending"),
}
SLA = {"basic": "72h response", "pro": "48h response", "business": "24h response", "business_pro": "12h response (priority human support)"}
INHERIT = {"pro": ["basic"], "business": ["basic", "pro"], "business_pro": ["basic", "pro", "business"], "ai_pro": ["basic", "pro", "business"],
           "ai_business": ["basic", "pro", "business", "ai_pro"], "ai_executive": ["basic", "pro", "business", "business_pro", "ai_pro", "ai_business"]}
MONEY = re.compile(r"(price|amount|invoice|card|refund|polar|webhook|payment)")  # no-money-gate-ok
def key(text):
    soon = "coming with anexochat" in text.lower()
    t = re.sub(r"\s*[—-]\s*coming with anexochat.*$", "", text, flags=re.I)
    s = re.sub(r"[^a-z0-9]+", "_", t.lower()).strip("_")
    for bad, ok in (("card", "panel"), ("payment", "settlement"), ("price", "rate"), ("amount", "sum")):  # a key may never spell a money word; the sentence is unchanged
        s = s.replace(bad, ok)
    s = ("soon_" if soon else "") + s
    if not s[:1].isalpha(): s = "f_" + s
    k = s[:50].rstrip("_") + "_" + hashlib.sha1(text.encode()).hexdigest()[:6]
    if not re.fullmatch(r"[a-z][a-z0-9_.]{1,60}", k) or MONEY.search(k): raise SystemExit("bad key " + k + " for " + text)
    return k
own = {pid: [key(f) for f in p["features"]] for pid, p in plans.items()}
def feats(pid):
    out = []
    for q in INHERIT.get(pid, []) + [pid]:
        for k in own[q]:
            if k not in out: out.append(k)
    return out
L = ["-- AD6b (ADMIN DESK SQL, 22 Nov 2026 PKT, GENERATED by scripts/gen-pkg-seed.py from src/lib/plans.ts, the published landing-page list): D5a-2 FILL of the AD6 registry.",
     "-- Features and limits only, never a price. Grace = 3 days (his payment rule: warning, service never blocked, sql/phase50). Trial 0 (the page promises none). Version 1 of each package; a later change is a NEW version.",
     "-- BUILT ON AD6 (schema-first, read in full): fadm_pkg, fadm_pkg_version, fadm_pkg_publish. Idempotent: a package that already has a version is left alone. One transaction.",
     "BEGIN;", "DO $$", "DECLARE o uuid; v int;", "BEGIN",
     "  SELECT id INTO o FROM desk.fadm_owner WHERE role = 'owner' AND active ORDER BY created_at LIMIT 1;",
     "  IF o IS NULL THEN RAISE EXCEPTION 'AD6b needs the owner row (AD1) to publish as' USING ERRCODE = 'no_data_found'; END IF;"]
for pid, p in plans.items():
    lim, src = LIM[pid]
    L.append(f"  -- {pid}: limits from the page: {src}")
    L.append(f"  IF NOT EXISTS (SELECT 1 FROM desk.fadm_pkg_version WHERE pkg_id = '{pid}') THEN")
    L.append(f"    v := desk.fadm_pkg_publish(o, '{pid}', '{p['name']}', current_date, '{json.dumps(feats(pid))}'::jsonb, '{json.dumps(lim)}'::jsonb, 0, 3, {('$s$'+SLA[pid]+'$s$') if pid in SLA else 'NULL'}, NULL);")
    L.append("  END IF;")
L += ["END $$;", "COMMIT;"]
open(os.path.join(ROOT, "docs/claude/admin-desk/sql/AD6b.sql"), "w").write("\n".join(L) + "\n")
print({k: len(feats(k)) for k in plans})
