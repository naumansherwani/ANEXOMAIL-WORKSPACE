  end if;
end $$;

-- ===============================================================================================================================================
-- 1) THE CURRENT PUBLIC KEY ON THE MAILBOX
-- ===============================================================================================================================================
alter table public.fmail_mailboxes add column if not exists recipient_pub bytea;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'fmail_mailboxes_pub_len_ck' and conrelid = 'public.fmail_mailboxes'::regclass) then
    alter table public.fmail_mailboxes add constraint fmail_mailboxes_pub_len_ck check (recipient_pub is null or octet_length(recipient_pub) = 1216);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'fmail_mailboxes_pub_id_ck' and conrelid = 'public.fmail_mailboxes'::regclass) then
    -- a public key without an id, or an id on an active pq mailbox without a key, is never allowed once a key was installed
    alter table public.fmail_mailboxes add constraint fmail_mailboxes_pub_id_ck check (recipient_pub is null or recipient_key_id is not null);
  end if;
end $$;

-- ===============================================================================================================================================
-- 2) KEY REGISTRY (append-only in spirit: rows are never deleted, the key bytes never change, only the status moves forward)
-- ===============================================================================================================================================
create table if not exists public.fmail_keys (
  id           uuid primary key default gen_random_uuid(),
  mailbox_id   uuid not null references public.fmail_mailboxes (id) on delete cascade,
  key_id       text not null check (key_id ~ '^[A-Za-z0-9._:-]{4,96}$'),
  pub          bytea not null check (octet_length(pub) = 1216),
  pub_sha256   bytea generated always as (sha256(pub)) stored,
  status       text not null default 'active' check (status in ('active', 'retired', 'revoked')),
  created_at   timestamptz not null default now(),
  created_by   uuid not null references public.founder_accounts (user_id) on delete restrict,
  touch_hash   text not null check (touch_hash ~ '^[0-9a-f]{64}$'),            -- sha256 of the passkey assertion that allowed it (never the assertion)
  retired_at   timestamptz,
  revoked_at   timestamptz,
  revoke_reason text check (revoke_reason is null or (length(btrim(revoke_reason)) between 8 and 300 and revoke_reason !~ '[[:cntrl:]]')),
  ledger_seq   bigint,
  -- degenerate keys are refused by the table itself: all-zero ML-KEM part or all-zero X25519 part
  constraint fmail_keys_not_zero_ck check (substring(pub from 1 for 1184) <> decode(repeat('00', 1184), 'hex') and substring(pub from 1185 for 32) <> decode(repeat('00', 32), 'hex')),
  constraint fmail_keys_state_ck check (
       (status = 'active'  and retired_at is null     and revoked_at is null     and revoke_reason is null)
    or (status = 'retired' and retired_at is not null and revoked_at is null     and revoke_reason is null)
    or (status = 'revoked' and revoked_at is not null and revoke_reason is not null)),
  unique (mailbox_id, key_id)
);
create unique index if not exists fmail_keys_one_active_uq on public.fmail_keys (mailbox_id) where status = 'active';
create unique index if not exists fmail_keys_pub_uq on public.fmail_keys (mailbox_id, pub_sha256);      -- the same key can never be installed twice
create index if not exists fmail_keys_box_ix on public.fmail_keys (mailbox_id, created_at desc);
alter table public.fmail_keys enable row level security;
alter table public.fmail_keys force row level security;
revoke all on public.fmail_keys from public, anon, authenticated;
grant select, insert, update on public.fmail_keys to service_role;

-- the key bytes and identity never change; the status only moves forward (active -> retired | revoked, retired -> revoked); nothing is deleted
create or replace function public.fmail_keys_guard_168() returns trigger language plpgsql set search_path = pg_catalog, public as $$
begin
  if tg_op = 'DELETE' then
    if exists (select 1 from public.fmail_mailboxes m where m.id = old.mailbox_id) then raise exception 'E168: a key row is never deleted (it is the proof of what a message was sealed to)' using errcode = '42501'; end if;
    return old;
  end if;
  if tg_op = 'UPDATE' then
    if new.mailbox_id <> old.mailbox_id or new.key_id <> old.key_id or new.pub <> old.pub or new.created_at <> old.created_at or new.created_by <> old.created_by or new.touch_hash <> old.touch_hash then
      raise exception 'E168: a registered key cannot be edited' using errcode = '42501';
    end if;
    if not ((old.status = new.status) or (old.status = 'active' and new.status in ('retired', 'revoked')) or (old.status = 'retired' and new.status = 'revoked')) then
      raise exception 'E168: key status cannot go from % to %', old.status, new.status using errcode = '42501';
    end if;
    if old.status = 'revoked' and (new.revoked_at is distinct from old.revoked_at or new.revoke_reason is distinct from old.revoke_reason) then
      raise exception 'E168: a revoked key stays revoked' using errcode = '42501';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists fmail_keys_guard on public.fmail_keys;
create trigger fmail_keys_guard before update or delete on public.fmail_keys for each row execute function public.fmail_keys_guard_168();

-- the mailbox key columns move ONLY through the two doors below (they raise the flag inside their own transaction)
create or replace function public.fmail_mailbox_keyguard_168() returns trigger language plpgsql set search_path = pg_catalog, public as $$
begin
  if (new.recipient_pub is distinct from old.recipient_pub or new.recipient_key_id is distinct from old.recipient_key_id)
     and coalesce(current_setting('fmail.key_door', true), '') <> 'on' then
    raise exception 'E168: change the mailbox key through fmail_key_register / fmail_key_revoke (passkey touch + ledger)' using errcode = '42501';
  end if;
  return new;
end $$;
drop trigger if exists fmail_mailbox_keyguard on public.fmail_mailboxes;
create trigger fmail_mailbox_keyguard before update on public.fmail_mailboxes for each row execute function public.fmail_mailbox_keyguard_168();

-- ===============================================================================================================================================
-- 3) DOOR: INSTALL OR ROTATE THE FOUNDER PUBLIC KEY (passkey touch required, always; ledger + anchor)
-- ===============================================================================================================================================
create or replace function public.fmail_key_register(p_actor uuid, p_mailbox uuid, p_key_id text, p_pub bytea, p_touch_hash text)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, extensions as $$
declare m public.fmail_mailboxes%rowtype; v_old public.fmail_keys%rowtype; v_led jsonb; v_rot boolean := false;
begin
  if p_touch_hash is null or p_touch_hash !~ '^[0-9a-f]{64}$' then raise exception 'E168: a passkey touch is required to install or rotate a mailbox key' using errcode = '42501'; end if;
  if p_key_id is null or p_key_id !~ '^[A-Za-z0-9._:-]{4,96}$' then raise exception 'E168: bad key id' using errcode = '22023'; end if;
  if p_pub is null or octet_length(p_pub) <> 1216 then raise exception 'E168: the public key must be exactly 1216 bytes (ML-KEM-768 1184 + X25519 32)' using errcode = '22023'; end if;
  select * into m from public.fmail_mailboxes where id = p_mailbox for update;
  if not found then raise exception 'E168: unknown mailbox' using errcode = '42704'; end if;
  if m.status = 'retired' then raise exception 'E168: a retired mailbox takes no new key' using errcode = '42501'; end if;
  if m.owner <> p_actor then raise exception 'E168: this mailbox belongs to another founder account' using errcode = '42501'; end if;
  select * into v_old from public.fmail_keys where mailbox_id = p_mailbox and status = 'active';
  if found then
    if v_old.key_id = p_key_id then raise exception 'E168: the new key needs a new id (rotation)' using errcode = '23505'; end if;
    v_rot := true;
  end if;
  if exists (select 1 from public.fmail_keys where mailbox_id = p_mailbox and pub_sha256 = sha256(p_pub)) then raise exception 'E168: this exact key was already registered for the mailbox' using errcode = '23505'; end if;
  perform set_config('fmail.key_door', 'on', true);
  if v_rot then update public.fmail_keys set status = 'retired', retired_at = now() where id = v_old.id; end if;
  v_led := public.fmail_ledger_append(p_actor, p_mailbox, case when v_rot then 'key_rotate' else 'key_import' end, p_key_id,
             case when v_rot then 'mailbox sealing key rotated (passkey touched)' else 'mailbox sealing key installed (passkey touched)' end,
             jsonb_build_object('key_id', p_key_id, 'fp', encode(sha256(p_pub), 'hex'), 'previous', case when v_rot then v_old.key_id else null end), true);
  insert into public.fmail_keys (mailbox_id, key_id, pub, created_by, touch_hash, ledger_seq) values (p_mailbox, p_key_id, p_pub, p_actor, p_touch_hash, (v_led ->> 'seq')::bigint);
  update public.fmail_mailboxes set recipient_key_id = p_key_id, recipient_pub = p_pub, seal_mode = 'recipient_pq',
         status = case when status = 'paused' then 'active' else status end where id = p_mailbox;
  perform set_config('fmail.key_door', 'off', true);
  return jsonb_build_object('ok', true, 'rotated', v_rot, 'key_id', p_key_id, 'fingerprint', encode(sha256(p_pub), 'hex'), 'ledger_seq', (v_led ->> 'seq')::bigint);
end $$;
revoke all on function public.fmail_key_register(uuid, uuid, text, bytea, text) from public, anon, authenticated;
grant execute on function public.fmail_key_register(uuid, uuid, text, bytea, text) to service_role;

-- ===============================================================================================================================================
-- 4) DOOR: REVOKE A KEY (compromise). The mailbox is paused, no public key is left, inbound is refused until a new key is registered.
-- ===============================================================================================================================================
create or replace function public.fmail_key_revoke(p_actor uuid, p_mailbox uuid, p_key_id text, p_reason text, p_touch_hash text)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, extensions as $$
declare k public.fmail_keys%rowtype; m public.fmail_mailboxes%rowtype; v_led jsonb;
begin
  if p_touch_hash is null or p_touch_hash !~ '^[0-9a-f]{64}$' then raise exception 'E168: a passkey touch is required to revoke a mailbox key' using errcode = '42501'; end if;
  if p_reason is null or length(btrim(p_reason)) < 8 or length(p_reason) > 300 or p_reason ~ '[[:cntrl:]]' then raise exception 'E168: give a real reason (8 to 300 characters)' using errcode = '22023'; end if;
  select * into m from public.fmail_mailboxes where id = p_mailbox for update;
  if not found or m.owner <> p_actor then raise exception 'E168: unknown mailbox' using errcode = '42704'; end if;
  select * into k from public.fmail_keys where mailbox_id = p_mailbox and key_id = p_key_id for update;
  if not found then raise exception 'E168: unknown key' using errcode = '42704'; end if;
  if k.status = 'revoked' then raise exception 'E168: key already revoked' using errcode = '23505'; end if;
  perform set_config('fmail.key_door', 'on', true);
  v_led := public.fmail_ledger_append(p_actor, p_mailbox, 'mailbox_lock', p_key_id, 'mailbox key revoked: ' || left(btrim(p_reason), 200),
             jsonb_build_object('key_id', p_key_id, 'was', k.status, 'fp', encode(k.pub_sha256, 'hex')), true);
  update public.fmail_keys set status = 'revoked', revoked_at = now(), revoke_reason = btrim(p_reason) where id = k.id;
  if k.status = 'active' then
    update public.fmail_mailboxes set recipient_pub = null, status = 'paused' where id = p_mailbox;
  end if;
  perform set_config('fmail.key_door', 'off', true);
  return jsonb_build_object('ok', true, 'key_id', p_key_id, 'mailbox_paused', k.status = 'active', 'ledger_seq', (v_led ->> 'seq')::bigint);
end $$;
revoke all on function public.fmail_key_revoke(uuid, uuid, text, text, text) from public, anon, authenticated;
grant execute on function public.fmail_key_revoke(uuid, uuid, text, text, text) to service_role;

-- ===============================================================================================================================================
-- 5) READ DOOR FOR THE RUST ENGINE: the LMTP RCPT command and the sealing step
--    accept = true only for an ACTIVE mailbox in recipient_pq mode that has a public key; otherwise a reason the engine turns into a 4xx / 5xx reply.
--    (A paused mailbox answers 450 = try later, so no mail is lost while he installs a new key; an unknown address answers 550.)
-- ===============================================================================================================================================
create or replace function public.fmail_rcpt_resolve(p_address text)
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare m public.fmail_mailboxes%rowtype; v_addr text := lower(btrim(coalesce(p_address, '')));
begin
  if length(v_addr) < 6 or length(v_addr) > 254 or v_addr ~ '[[:cntrl:][:space:]]' then return jsonb_build_object('accept', false, 'reason', 'bad_address', 'smtp', 501); end if;
  select * into m from public.fmail_mailboxes where address = v_addr;
  if not found then return jsonb_build_object('accept', false, 'reason', 'unknown_mailbox', 'smtp', 550); end if;
  if m.status = 'retired' then return jsonb_build_object('accept', false, 'reason', 'retired', 'smtp', 550); end if;
  if m.status in ('paused', 'locked') then return jsonb_build_object('accept', false, 'reason', 'paused', 'smtp', 450); end if;
  if m.seal_mode = 'recipient_pq' and m.recipient_pub is null then return jsonb_build_object('accept', false, 'reason', 'no_key', 'smtp', 450); end if;
  return jsonb_build_object('accept', true, 'mailbox_id', m.id, 'brand', m.brand, 'seal_mode', m.seal_mode, 'key_id', m.recipient_key_id, 'vault_key_id', m.vault_key_id,
                            'recipient_pub_hex', case when m.recipient_pub is null then null else encode(m.recipient_pub, 'hex') end);
end $$;
revoke all on function public.fmail_rcpt_resolve(text) from public, anon, authenticated;
grant execute on function public.fmail_rcpt_resolve(text) to service_role;

-- the key history the Keys screen shows (no key bytes, only ids, fingerprints and states)
create or replace function public.fmail_key_history(p_mailbox uuid)
returns table (key_id text, status text, fingerprint text, created_at timestamptz, retired_at timestamptz, revoked_at timestamptz, ledger_seq bigint)
language sql stable security definer set search_path = pg_catalog, public as $$
  select k.key_id, k.status, encode(k.pub_sha256, 'hex'), k.created_at, k.retired_at, k.revoked_at, k.ledger_seq from public.fmail_keys k where k.mailbox_id = p_mailbox order by k.created_at desc, k.id;
$$;
revoke all on function public.fmail_key_history(uuid) from public, anon, authenticated;
grant execute on function public.fmail_key_history(uuid) to service_role;

-- ===============================================================================================================================================
-- 6) BRIDGE FEED: the mail lanes for the founder BridgeMap. Counts of the last p_hours (1..168) from real rows and the real ledger; nothing invented.
--    lane = stable id, dir = in | out, tone = ok | warn | bad (the UI picks the colour; bad only when something needs him).
-- ===============================================================================================================================================
create or replace function public.fmail_bridge_feed(p_hours int default 24)
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_h int := least(greatest(coalesce(p_hours, 24), 1), 168); v_since timestamptz; v_since_ms bigint; lanes jsonb := '[]'::jsonb;
        n bigint; t bigint;
begin
  v_since := now() - make_interval(hours => v_h); v_since_ms := (extract(epoch from v_since) * 1000)::bigint;
  select count(*), coalesce(max((extract(epoch from received_at) * 1000)::bigint), 0) into n, t from public.fmail_messages where direction = 'in' and received_at >= v_since;
  lanes := lanes || jsonb_build_object('lane', 'mail-in', 'label', 'Mail in', 'dir', 'in', 'count', n, 'last_ms', t, 'tone', 'ok');
  select count(*), coalesce(max(ts_ms), 0) into n, t from public.fmail_ledger where action = 'quarantine_in' and ts_ms >= v_since_ms;
  lanes := lanes || jsonb_build_object('lane', 'mail-quarantine', 'label', 'Quarantined', 'dir', 'in', 'count', n, 'last_ms', t, 'tone', case when n > 0 then 'warn' else 'ok' end);
  select count(*), coalesce(max(ts_ms), 0) into n, t from public.fmail_ledger where action = 'inbound_reject' and ts_ms >= v_since_ms;
  lanes := lanes || jsonb_build_object('lane', 'mail-rejected', 'label', 'Rejected', 'dir', 'in', 'count', n, 'last_ms', t, 'tone', 'ok');
  select count(*), coalesce(max(ts_ms), 0) into n, t from public.fmail_ledger where action = 'send_ok' and ts_ms >= v_since_ms;
  lanes := lanes || jsonb_build_object('lane', 'mail-out', 'label', 'Mail out', 'dir', 'out', 'count', n, 'last_ms', t, 'tone', 'ok');
  select count(*), coalesce(max(ts_ms), 0) into n, t from public.fmail_ledger where action = 'send_fail' and ts_ms >= v_since_ms;
  lanes := lanes || jsonb_build_object('lane', 'mail-failed', 'label', 'Send failed', 'dir', 'out', 'count', n, 'last_ms', t, 'tone', case when n > 0 then 'bad' else 'ok' end);
  select count(*) into n from public.fmail_outbox where state in ('queued', 'scheduled', 'sending');
  lanes := lanes || jsonb_build_object('lane', 'mail-queued', 'label', 'Queued / scheduled', 'dir', 'out', 'count', n, 'last_ms', 0, 'tone', 'ok');
  select count(*) into n from public.fmail_messages where direction = 'in' and scan_state = 'pending';
  lanes := lanes || jsonb_build_object('lane', 'mail-scan', 'label', 'Waiting for virus scan', 'dir', 'in', 'count', n, 'last_ms', 0, 'tone', case when n > 20 then 'warn' else 'ok' end);
  return jsonb_build_object('hours', v_h, 'lanes', lanes,
    'unread', (select count(*) from public.fmail_messages x join public.fmail_folders f on f.id = x.folder_id where x.direction = 'in' and not x.is_read and f.kind = 'inbox'),
    'mailboxes_active', (select count(*) from public.fmail_mailboxes where status = 'active'),
    'mailboxes_without_key', (select count(*) from public.fmail_mailboxes where status = 'active' and seal_mode = 'recipient_pq' and recipient_pub is null),
    'ledger_head', (select coalesce(max(seq), 0) from public.fmail_ledger));
end $$;
revoke all on function public.fmail_bridge_feed(int) from public, anon, authenticated;
grant execute on function public.fmail_bridge_feed(int) to service_role;

-- ===============================================================================================================================================
-- 7) POSTURE
-- ===============================================================================================================================================
create or replace function public.fmail_posture168()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
begin
  return jsonb_build_object(
    'keys_rls', coalesce((select c.relrowsecurity and c.relforcerowsecurity from pg_class c where c.oid = to_regclass('public.fmail_keys')), false),
    'anon_can_read', has_table_privilege('anon', 'public.fmail_keys', 'select') or has_table_privilege('authenticated', 'public.fmail_keys', 'select'),
    'mailboxes_with_two_active_keys', (select count(*) from (select mailbox_id from public.fmail_keys where status = 'active' group by 1 having count(*) > 1) x),
    'mailbox_pub_mismatch', (select count(*) from public.fmail_mailboxes m where m.recipient_pub is not null
                               and not exists (select 1 from public.fmail_keys k where k.mailbox_id = m.id and k.status = 'active' and k.key_id = m.recipient_key_id and k.pub = m.recipient_pub)),
    'active_pq_mailboxes_without_key', (select count(*) from public.fmail_mailboxes where status = 'active' and seal_mode = 'recipient_pq' and recipient_pub is null),
    'guard_triggers', (select count(*) from pg_trigger where tgname in ('fmail_keys_guard', 'fmail_mailbox_keyguard') and not tgisinternal));
end $$;
revoke all on function public.fmail_posture168() from public, anon, authenticated;
grant execute on function public.fmail_posture168() to service_role;

-- ===============================================================================================================================================
-- 8) SELFTEST (rolls itself back through the P0777 sentinel; writes nothing that stays)
-- ===============================================================================================================================================
create or replace function public.fmail_selftest168()
returns jsonb language plpgsql security definer set search_path = pg_catalog, public, extensions as $$
declare
  res jsonb := '[]'::jsonb; v_actor uuid; v_box uuid; v_out jsonb; v_n int; v_pass int; v_fail int; v_txt text; v_j jsonb;
  k1 bytea := decode(repeat('07', 1216), 'hex'); k2 bytea := decode(repeat('09', 1216), 'hex'); kz bytea := decode(repeat('00', 1216), 'hex');
  kx bytea := decode(repeat('07', 1184) || repeat('00', 32), 'hex');
  t1 text := repeat('a', 64); t2 text := repeat('b', 64); v_seq0 bigint;
begin
  select user_id into v_actor from public.founder_accounts limit 1;
  if v_actor is null then return jsonb_build_object('ok', false, 'error', 'no founder account to test with'); end if;
  select coalesce(max(seq), 0) into v_seq0 from public.fmail_ledger;
  begin
    insert into public.fmail_mailboxes (owner, address, brand, status, seal_mode) values (v_actor, 'selftest168@anexomail.com', 'anexomail', 'paused', 'recipient_pq') returning id into v_box;
    v_j := public.fmail_rcpt_resolve('selftest168@anexomail.com');
    res := res || jsonb_build_object('name', 'paused mailbox without a key answers 450 (try later)', 'ok', not (v_j ->> 'accept')::boolean and (v_j ->> 'smtp')::int = 450);
    v_j := public.fmail_rcpt_resolve('nobody-selftest168@anexomail.com');
    res := res || jsonb_build_object('name', 'unknown address answers 550', 'ok', not (v_j ->> 'accept')::boolean and (v_j ->> 'smtp')::int = 550);
    v_j := public.fmail_rcpt_resolve(E'bad\naddress@x');
    res := res || jsonb_build_object('name', 'control characters in the address answer 501', 'ok', (v_j ->> 'smtp')::int = 501);

    begin perform public.fmail_key_register(v_actor, v_box, 'pqk-t-1', k1, null); res := res || jsonb_build_object('name', 'key install without a touch refused', 'ok', false);
    exception when others then res := res || jsonb_build_object('name', 'key install without a touch refused', 'ok', true); end;
    begin perform public.fmail_key_register(v_actor, v_box, 'pqk-t-1', substring(k1 from 1 for 1215), t1); res := res || jsonb_build_object('name', 'key of the wrong length refused', 'ok', false);
    exception when others then res := res || jsonb_build_object('name', 'key of the wrong length refused', 'ok', true); end;
    begin perform public.fmail_key_register(v_actor, v_box, 'pqk-t-1', kz, t1); res := res || jsonb_build_object('name', 'all-zero key refused', 'ok', false);
    exception when others then res := res || jsonb_build_object('name', 'all-zero key refused', 'ok', true); end;
