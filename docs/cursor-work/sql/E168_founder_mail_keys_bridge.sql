
-- E168 - FOUNDER MAILBOX KEYS + RCPT DOOR + BRIDGE FEED (phase Q1b-2). Advanced level, sits on E167 and changes nothing of it.
-- ---------------------------------------------------------------------------------------------------------------------------------------------------
-- WHY: E167 stores only the key ID the messages are sealed to. The Rust inbound engine (fmail_kem.rs) must wrap each message key to the founder's PUBLIC key
-- (ML-KEM-768 + X25519 = 1216 bytes), so the database has to hold that public key, know its history, and refuse every other way to change it.
--   * fmail_mailboxes.recipient_pub   the CURRENT public key (1216 bytes), only ever changed through fmail_key_register / fmail_key_revoke
--   * fmail_keys                      the key registry: every key a mailbox ever had (active | retired | revoked), pub immutable, rows never deleted,
--                                     one ACTIVE key per mailbox (partial unique index), SHA-256 fingerprint generated by the database
--   * fmail_key_register              the only door to install or rotate a key: passkey touch REQUIRED, old key retired, ledger row (key_import / key_rotate)
--                                     anchored into the founder audit chain. Mail sealed to an older key stays readable by that older private key.
--   * fmail_key_revoke                a compromised key: revoked, mailbox PAUSED (no public key left, inbound is refused), ledger (mailbox_lock) anchored
--   * fmail_rcpt_resolve              the single read door of the LMTP RCPT command: address -> accept / reject reason + mailbox + key id + public key
--   * fmail_bridge_feed               the lane counters the founder BridgeMap shows for mail (in, quarantine, rejected, out, failed, queued, scan pending)
--   * fmail_posture168 / fmail_selftest168 (rolls itself back) / CHECK_E168
-- NOTHING of awam is touched (CORE FREEZE + separation law). All objects are fmail_* / ..168, service_role only, RLS forced.
-- Run again any time: create ... if not exists / create or replace. Needs E167 and E100.

set lock_timeout = '10s';
set statement_timeout = '120s';
set search_path = pg_catalog, public, extensions;

