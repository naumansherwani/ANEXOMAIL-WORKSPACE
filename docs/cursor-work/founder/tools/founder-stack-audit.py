#!/usr/bin/env python3
"""Static scan (Rule 22): which data calls do the FOUNDER pages make, and by which road?
  rust-first  = rpcOrRest("proc", {path})  -> tries Rust /rpc/proc, FALLS BACK to Bun REST path on 404/501/502/503/0
  rust-only   = rpc("proc")                -> Rust only
  bun-only    = api("/api/...") / fetch    -> Bun/Brain REST only (no Rust road at all)
Usage: python3 docs/cursor-work/founder/tools/founder-stack-audit.py [rust-procs.txt] > docs/cursor-work/founder/founder-stack-audit.md
rust-procs.txt (optional) = output of docs/cursor-work/server/rust-procs-check.sh section 1 (one proc per line) -> marks which rust-first procs really exist in Rust.
"""
import re, glob, sys, collections
REPO = "."
routes = sorted(glob.glob(f"{REPO}/src/routes/app.founder*.tsx") + glob.glob(f"{REPO}/src/routes/founder*.tsx"))
use = collections.defaultdict(set)  # lib -> routes
for r in routes:
    t = open(r, encoding="utf-8").read()
    for m in re.finditer(r'from "@/lib/([A-Za-z0-9_\-/]+)"', t):
        use[m.group(1)].add(r.split("/")[-1].replace(".tsx", ""))
rust_ok = None
if len(sys.argv) > 1:
    rust_ok = set(x.strip() for x in open(sys.argv[1], encoding="utf-8") if x.strip() and not x.startswith("#"))

STR = r'''(?:"([^"]+)"|'([^']+)'|`([^`]+)`)'''
def lit(m, i=1): return next((g for g in m.groups()[i-1:i+2] if g), "")
rows = []  # (lib, kind, proc, path)
for lib in sorted(use):
    f = f"{REPO}/src/lib/{lib}.ts"
    try: t = open(f, encoding="utf-8").read()
    except FileNotFoundError:
        try: t = open(f + "x", encoding="utf-8").read()
        except FileNotFoundError: continue
    # wrapper helpers: const get = <T>(procedure: string, path: string ...) => rpcOrRest(...)
    wrappers = set(re.findall(r'(?:const|function)\s+(\w+)\s*=?\s*<[^>]*>\s*\(\s*(?:procedure|proc|name)\s*:\s*string\s*,\s*(?:path|rest)\s*:', t))
    names = ["rpcOrRest"] + sorted(wrappers)
    for n in names:
        for m in re.finditer(n + r'\s*(?:<[^()]*?>)?\s*\(\s*' + STR + r'\s*,\s*(?:\{\s*path:\s*)?' + STR, t):
            proc = next(g for g in m.groups()[:3] if g); path = next(g for g in m.groups()[3:] if g)
            rows.append((lib, "rust-first", proc, path))
    for m in re.finditer(r'(?<![\w.])rpc\s*(?:<[^()]*?>)?\s*\(\s*' + STR, t):
        rows.append((lib, "rust-only", next(g for g in m.groups() if g), ""))
    for m in re.finditer(r'(?<![\w.])api\s*(?:<[^()]*?>)?\s*\(\s*' + STR, t):
        rows.append((lib, "bun-only", "", next(g for g in m.groups() if g)))
    for m in re.finditer(r'fetch\(\s*' + STR, t):
        p = next(g for g in m.groups() if g)
        if "/api/" in p or "/rpc/" in p: rows.append((lib, "bun-only", "", p))
seen = set(); uniq = []
for r in rows:
    if r in seen: continue
    seen.add(r); uniq.append(r)
cnt = collections.Counter(k for _, k, _, _ in uniq)
print("# Founder stack audit (Rule 22) — static scan")
print()
print("Founder workspace ka maqsad: **sirf Rust** (tRPC `/rpc/*`, WebTransport/QUIC). Yeh scan repo ke code se batata hai ke founder pages ki kaun si calls abhi **Bun REST** par ja sakti hain. *Yeh static scan hai: Rust mein proc sach mein hai ya nahi — `server/rust-procs-check.sh` se milao (Rule 15).*")
print()
print(f"- Founder routes: **{len(routes)}**, unki libs: **{len(use)}**")
print(f"- **rust-first (Bun fallback maujood): {cnt['rust-first']}** · **rust-only: {cnt['rust-only']}** · **bun-only (Rust road hi nahi): {cnt['bun-only']}**")
if rust_ok is not None:
    miss = [u for u in uniq if u[1] == 'rust-first' and u[2] not in rust_ok]
    print(f"- Rust proc list diya gaya: rust-first mein se **{len(miss)}** procs Rust mein NAHI mile (yani abhi sach mein Bun par chal rahe hain)")
print()
for lib in sorted(use):
    rs = [u for u in uniq if u[0] == lib]
    if not rs: continue
    print(f"## `{lib}` — founder pages: {', '.join(sorted(use[lib]))}")
    print()
    print("| road | Rust proc | REST (Bun) path | Rust mein? |")
    print("|---|---|---|---|")
    for _, k, proc, path in rs:
        ex = "" if rust_ok is None or k != "rust-first" else ("haan" if proc in rust_ok else "**NAHI**")
        print(f"| {k} | {('`'+proc+'`') if proc else ''} | {('`'+path+'`') if path else ''} | {ex} |")
    print()

import os
if os.environ.get("PROCS_OUT"):
    with open(os.environ["PROCS_OUT"], "w", encoding="utf-8") as fh:
        fh.write("# founder pages ke rust-first/rust-only procs (generated by founder-stack-audit.py) — rust-procs-check.sh isko padhta hai\n")
        for p_ in sorted({u[2] for u in uniq if u[1] in ("rust-first", "rust-only") and u[2]}):
            fh.write(p_ + "\n")
