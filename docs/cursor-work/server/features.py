#!/usr/bin/env python3
"""FEATURE REGISTRY (his 18 Nov 2026 08:07 order: 'AUTO FEATURES SYSTEM, repo tells you what is missing, fix it BEFORE commit').
Every feature of a phase is one entry in docs/claude/features/<phase>.json: id, sub-phase (part), title, technology, status and MARKERS (file + regex that must exist when the feature is really in the code).
  built       all markers must be found in the repo (a 'written' feature that is absent FAILS the gate)
  todo        not written; if all its markers are found anyway the gate says 'it exists, mark it built' (so the list can never lie in the other direction)
  needs-haan  a UI addition he must approve first (same marker rule as todo)
  deferred    belongs to another phase, tracked only
A sub-phase that Q-STATE says is done cannot have a feature that is neither built nor deferred.
  features.py show            numbered list with status, missing markers, what is still to write
  features.py check           the gate (prints errors, exit 1)
  features.py render          rewrites docs/claude/FEATURES-LIVE.md and the compact block at the top of docs/claude/PHASE-NOW.md
  features.py set <id> <status>
"""
import glob, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
LIVE = os.path.join(ROOT, "docs/claude/FEATURES-LIVE.md"); PN = os.path.join(ROOT, "docs/claude/PHASE-NOW.md")
BEG, END = "<!--FEATURES-->", "<!--/FEATURES-->"
OK = ("built", "todo", "needs-haan", "deferred")
def files(): return sorted(glob.glob(os.path.join(ROOT, "docs/claude/features/*.json")))
def load(): return [(p, json.load(open(p))) for p in files()]
def found(m):
    p = os.path.join(ROOT, m["file"])
    if not os.path.isfile(p): return False
    try: return re.search(m["pattern"], open(p, errors="ignore").read(), re.M) is not None
    except re.error: return False
def state(f):
    ms = f.get("markers", []); have = [found(m) for m in ms]
    return have
def qdone():
    try:
        import importlib.util as iu
        sp = iu.spec_from_file_location("qstate", os.path.join(ROOT, "docs/cursor-work/server/qstate.py")); q = iu.module_from_spec(sp); sp.loader.exec_module(q)
        return {k for k, v in q.status().items() if v[0] == "done"}
    except Exception:
        return set()
def errors():
    out = []; done = qdone()
    for p, d in load():
        for f in d["features"]:
            if f["status"] not in OK: out.append(f'{f["id"]}: unknown status {f["status"]}'); continue
            have = state(f)
            if f["status"] == "built":
                miss = [m["file"] + " ~ " + m["pattern"] for m, h in zip(f["markers"], have) if not h]
                if not f["markers"]: out.append(f'{f["id"]}: a built feature must name its markers')
                if miss: out.append(f'{f["id"]} "{f["title"][:60]}" is marked BUILT but is NOT in the repo: ' + "; ".join(miss) + " (write it, or set it todo)")
            elif f["status"] in ("todo", "needs-haan") and f["markers"] and all(have):
                out.append(f'{f["id"]} "{f["title"][:60]}" exists in the repo but is marked {f["status"]}: python3 docs/cursor-work/server/features.py set {f["id"]} built')
            if f["part"] in done and f["status"] not in ("built", "deferred"):
                out.append(f'{f["id"]} "{f["title"][:60]}": the sub-phase {f["part"]} is DONE in Q-STATE but this feature is {f["status"]} (a phase is green only with every feature written)')
    t = open(LIVE).read() if os.path.isfile(LIVE) else ""
    if t != live_text(): out.append("docs/claude/FEATURES-LIVE.md is stale: python3 docs/cursor-work/server/features.py render")
    pn = open(PN).read() if os.path.isfile(PN) else ""
    if BEG not in pn or END not in pn or pn[pn.index(BEG):pn.index(END) + len(END)] != compact(): out.append("PHASE-NOW.md features block is stale: python3 docs/cursor-work/server/features.py render")
    return out
def mark(f):
    s = f["status"]; have = state(f)
    if s == "built": return "BUILT" if all(have) else "BUILT-BUT-MISSING"
    return {"todo": "TODO", "needs-haan": "NEEDS HIS HAAN", "deferred": "DEFERRED (Qtls)"}[s]
def live_text():
    L = ["# FEATURES LIVE (generated by docs/cursor-work/server/features.py from docs/claude/features/*.json: do not edit by hand)", "",
         "Every feature of a phase, one line each, checked against the repo (a built feature must be found in the code; a missing one is listed as TODO). Gate: rules-gate FEATURES.", ""]
    for p, d in load():
        n = len(d["features"]); b = sum(1 for f in d["features"] if f["status"] == "built")
        L += [f'## {d["phase"]}: {b} of {n} written ({d.get("written", "")})', ""]
        for f in d["features"]: L.append(f'- {f["id"]} [{mark(f)}] {f["title"]} | {f["tech"]}')
        L.append("")
    return "\n".join(L)
def compact():
    L = [BEG, "## FEATURES (auto, from docs/claude/features/*.json, full list docs/claude/FEATURES-LIVE.md; a missing feature is fixed BEFORE a commit, his 18 Nov 08:07 order)"]
    for p, d in load():
        b = sum(1 for f in d["features"] if f["status"] == "built"); L.append(f'{d["phase"]}: {b}/{len(d["features"])} written. NOT WRITTEN: ' + ", ".join(f["id"] for f in d["features"] if f["status"] in ("todo", "needs-haan")))
    L.append(END); return "\n".join(L)
def render():
    open(LIVE, "w").write(live_text())
    pn = open(PN).read()
    if BEG in pn and END in pn: pn = pn[:pn.index(BEG)] + compact() + pn[pn.index(END) + len(END):]
    else: pn = compact() + "\n" + pn
    open(PN, "w").write(pn)
def show():
    for p, d in load():
        print(f'== {d["phase"]} ==')
        for f in d["features"]:
            miss = [m["pattern"] for m, h in zip(f["markers"], state(f)) if not h]
            print(f'  {f["id"]:10} {mark(f):18} {f["title"][:90]}' + (f'   (missing in repo: {miss[0][:50]})' if miss and f["status"] != "deferred" else ""))
def set_status(i, st):
    for p, d in load():
        for f in d["features"]:
            if f["id"] == i:
                f["status"] = st; json.dump(d, open(p, "w"), indent=1); render(); print("set", i, st); return
    print("no such feature", i); sys.exit(1)
if __name__ == "__main__":
    c = sys.argv[1] if len(sys.argv) > 1 else "show"
    if c == "show": show()
    elif c == "render": render(); print("rendered")
    elif c == "set": set_status(sys.argv[2], sys.argv[3])
    elif c == "check":
        e = errors()
        for x in e: print("FAIL", x)
        print("features: ok" if not e else f"features: {len(e)} problem(s)"); sys.exit(1 if e else 0)
