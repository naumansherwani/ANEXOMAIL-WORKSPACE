#!/usr/bin/env bash
# Builds the SQL-editor files (his rule 25 Nov 2026 05:51: SQL runs in his SQL editor, the CHECK runs on his server): <ADnn>-editor.sql = [legacy rename for AD34] + ADnn.sql + the CHECK LAST (an editor shows only the last result).
cd "$(dirname "$0")/../sql"
for n in AD34 AD35; do
  { echo "-- $n EDITOR FILE (generated by tests/make-editor-sql.sh, do not edit): paste ALL of it into the SQL editor, run once. Last result = the CHECK, every row must be true. Order: AD34 first, then AD35."
    [ "$n" = AD34 ] && { echo "-- 1/3 legacy rename (renames the old non-fadm_ tables, nothing is deleted)"; cat legacy-rename.sql; echo "-- 2/3 $n.sql"; } || echo "-- 1/2 $n.sql"
    cat $n.sql; echo; echo "-- last: the $n CHECK"; cat checks/$n-check.sql; } > editor/$n-editor.sql
done
wc -l editor/*.sql
