export const DEFAULT_LOCALE = LOCALES[0]!;

export const STORAGE_KEY = "ax.locale";

export function findLocale(tag: string | null | undefined): Locale | undefined {
  if (!tag) return undefined;
  const lower = tag.toLowerCase();
  return (
    LOCALES.find((l) => l.tag.toLowerCase() === lower) ??
    LOCALES.find((l) => l.tag.toLowerCase().split("-")[0] === lower.split("-")[0])
  );
}

/** Flag emoji from a two-letter region code (no image assets needed). */
export function flagOf(region: string): string {
  return region
    .toUpperCase()
    .replace(/[A-Z]/g, (c) => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65));
}
