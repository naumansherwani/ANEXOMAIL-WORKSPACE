/**
 * CRM + future-page chrome for the 28 awam locales.
 * Key = English source. Missing = English. No dummy copy.
 */
function pack(keys: readonly string[], values: readonly string[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (let i = 0; i < keys.length; i += 1) {
    const key = keys[i];
    const value = values[i];
    if (key && value) out[key] = value;
  }
  return out;
}

