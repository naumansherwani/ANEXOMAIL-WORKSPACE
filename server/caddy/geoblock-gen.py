#!/usr/bin/env python3
"""GEO1 — Caddy country wall (founder 2 Nov 2026: Afghanistan, Israel, North Korea are not served; Caddy is the edge, no Cloudflare, no nginx).
Reads the public RIR "delegated" lists (APNIC for AF and KP, RIPE NCC for IL), turns the address ranges of those countries into CIDRs
and writes ONE Caddy snippet file. stdlib only. No account, no API key, no plugin.

  python3 geoblock-gen.py gen   <apnic-file> <ripe-file> <out.caddy>      write the snippet (used by geoblock.sh)
  python3 geoblock-gen.py wire  <Caddyfile> <sites-dir> [--dry]           add `import geoblock` to every anexomail.com site block (idempotent)
Honest limit: an address space that is registered with another RIR (transfers) is not in these two lists; a VPN exit in another country looks like that country.
"""
import ipaddress, re, sys, os

COUNTRIES = {"AF": "apnic", "KP": "apnic", "IL": "ripe", "SY": "ripe"}


def cidrs_from_delegated(text, want):
    out = {c: [] for c in want}
    for line in text.splitlines():
        if not line or line[0] == "#":
            continue
        p = line.split("|")
        if len(p) < 7 or p[1] not in want or p[2] not in ("ipv4", "ipv6") or p[6].strip() not in ("allocated", "assigned"):
            continue
        try:
            if p[2] == "ipv4":
                first = ipaddress.IPv4Address(p[3])
                last = ipaddress.IPv4Address(int(first) + int(p[4]) - 1)
                out[p[1]].extend(str(n) for n in ipaddress.summarize_address_range(first, last))
            else:
                out[p[1]].append(str(ipaddress.IPv6Network(f"{p[3]}/{int(p[4])}", strict=False)))
        except ValueError:
            continue
    return out


def snippet(all_cidrs):
    flat = sorted({c for v in all_cidrs.values() for c in v}, key=lambda x: (":" in x, ipaddress.ip_network(x).network_address))
    lines = ["# GEO1 country wall - generated by server/caddy/geoblock-gen.py (do not edit by hand; re-run geoblock.sh apply to refresh).",
             "# Countries: " + ", ".join(f"{c}={len(v)} ranges" for c, v in sorted(all_cidrs.items())),
             "(geoblock) {", "\t@geoblocked remote_ip " + " ".join(flat) if flat else "\t@geoblocked remote_ip 192.0.2.1/32",
             "\tlog_skip @geoblocked", "\thandle @geoblocked {", "\t\theader Cache-Control \"no-store\"",
             "\t\trespond \"ANEXOMAIL is not available in your country.\" 403", "\t}", "}", ""]
    return "\n".join(lines)


SITE_RE = re.compile(r"^([^\s#{][^{\n]*)\{\s*$")


def wire_text(src):
    """Insert `import geoblock` as the first line of every top-level site block whose address contains anexomail.com. Returns (new_text, changed_hosts)."""
    out, changed, depth, i = [], [], 0, 0
    lines = src.split("\n")
    while i < len(lines):
        ln = lines[i]
        out.append(ln)
        if depth == 0:
            m = SITE_RE.match(ln)
            if m and "anexomail.com" in m.group(1) and not m.group(1).strip().startswith("("):
                nxt = lines[i + 1] if i + 1 < len(lines) else ""
                if "import geoblock" not in nxt:
                    out.append("\timport geoblock")
                    changed.append(m.group(1).strip())
        depth += ln.count("{") - ln.count("}")
        i += 1
    return "\n".join(out), changed


def main(a):
    if len(a) >= 5 and a[1] == "gen":
        ap, rp, outp = a[2], a[3], a[4]
        res = {}
        for c, reg in COUNTRIES.items():
            res.update(cidrs_from_delegated(open(ap if reg == "apnic" else rp, errors="replace").read(), [c]))
        for c in COUNTRIES:
            if not res.get(c):
                print(f"FAIL: no ranges found for {c} - refusing to write an empty wall", file=sys.stderr)
                return 2
        open(outp, "w").write(snippet(res))
        print(" ".join(f"{c}={len(res[c])}" for c in sorted(res)))
        return 0
    if len(a) >= 4 and a[1] == "wire":
        main_f, sites, dry = a[2], a[3], "--dry" in a
        files = [main_f] + sorted(os.path.join(sites, f) for f in os.listdir(sites) if f.endswith(".caddy")) if os.path.isdir(sites) else [main_f]
        total = 0
        for f in files:
            s = open(f).read()
            t, ch = wire_text(s)
            if f == main_f and "import /etc/caddy/geoblock.caddy" not in t:
                t = "import /etc/caddy/geoblock.caddy\n" + t
                ch = ch or ["(import line only)"]
            if ch:
                total += len(ch)
                print(f"{'would change' if dry else 'changed'} {f}: {', '.join(ch)}")
                if not dry:
                    open(f, "w").write(t)
        print(f"blocks wired: {total}")
        return 0
    print(__doc__)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
