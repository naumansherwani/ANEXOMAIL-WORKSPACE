#!/usr/bin/env bash
# F2b: the founder SPA ships the SAME kernel build as the user site (Rule 52: one kernel). Run after scripts/build-kernel.sh, before `vite build`.
# Copies public/kernel/anexo-kernel-<ver>.wasm into founder-web/public/kernel/ and writes src/kernel.pin.ts (version + SHA-256) from the user site's pin.
set -euo pipefail
cd "$(dirname "$0")"
PIN=../src/lib/kernel/pin.gen.ts
VER=$(grep -m1 'version:' $PIN | cut -d'"' -f2); SHA=$(grep -m1 'sha256:' $PIN | cut -d'"' -f2)
SRC=../public/kernel/anexo-kernel-$VER.wasm
[ "$(sha256sum "$SRC" | cut -d' ' -f1)" = "$SHA" ] || { echo "FAIL: $SRC does not match its pin"; exit 1; }
mkdir -p public/kernel && find public/kernel -name 'anexo-kernel-*.wasm' ! -name "anexo-kernel-$VER.wasm" -delete
cp "$SRC" public/kernel/
cat > src/kernel.pin.ts <<EOT
// GENERATED by kernel-sync.sh from the user site's kernel pin (same build, Rule 52). Do not edit by hand.
export const KERNEL = { version: "$VER", url: "/_cc/kernel/anexo-kernel-$VER.wasm", sha256: "$SHA" } as const;
EOT
echo "founder kernel $VER sha256 $SHA"
